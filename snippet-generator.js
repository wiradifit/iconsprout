/**
 * snippet-generator.js
 * Produces a ready-to-paste HTML <head> block with <link> and <meta> tags
 * for apple-touch-icon, android-chrome, favicon.ico, and favicon sizes.
 */
(function (global) {
  'use strict';

  /**
   * Default favicon sizes to generate <link> tags for.
   */
  var FAVICON_SIZES = [16, 32, 48, 72, 96, 128, 144, 152, 192, 384, 512];

  /**
   * Default color configuration. Overridden when a detected background color
   * is supplied via the options argument.
   */
  var DEFAULT_COLORS = {
    theme_color: '#000000',
    background_color: '#ffffff',
    title: 'Favicon Bundle',
    description: 'Generated favicon HTML snippet'
  };

  /**
   * Build a complete HTML <head> snippet string from the favicon file map.
   *
   * @param {Object} fileMap     – Keyed map produced by favicon-generator.js.
   *                               Expected shape:
   *               {
   *                 'image/x-icon':   { src: 'favicon.ico' },
   *                 'image/png':      {
   *                   '16x16':  { src: 'favicon-16x16.png' },
   *                   '32x32':  { src: 'favicon-32x32.png' },
   *                   ...
   *                 },
   *                 'image/webp':     { ... }
   *               }
   * @param {Object} [options]   – Optional overrides.
   * @param {string} [options.baseUrl='']      – Prefix prepended to every src URL.
   * @param {string} [options.iconTitle]       – Title attribute on <link rel="icon">.
   * @param {string} [options.iconType]        – MIME type for the fallback <link rel="icon">.
   * @param {Object} [options.colors]          – Theme / bg / tile colour overrides.
   * @returns {string} Fully formed HTML snippet safe for innerText / clipboard paste.
   */
  function snippet(fileMap, options) {
    options    = options || {};
    var baseUrl = options.baseUrl || '';

    // Merge supplied colour config onto defaults so properties are never undefined.
    var colors = Object.create(null);
    Object.keys(DEFAULT_COLORS).forEach(function (key) {
      colors[key] = (options.colors && options.colors[key])
        ? String(options.colors[key])
        : DEFAULT_COLORS[key];
    });

    /**
     * Escape a string for safe inclusion inside an HTML attribute value.
     * Replaces &, <, >, ", and ' to prevent attribute injection.
     */
    function esc(str) {
      return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
    }

    var lines = [];

    // ── Meta: page title & description (helps screen-readers & preview cards) ──
    lines.push('<!-- favicons & manifest -->');
    lines.push('<meta charset="utf-8">');
    lines.push('<title>' + esc(colors.title) + '</title>');
    lines.push('<meta name="description" content="' + esc(colors.description) + '">');
    lines.push('<meta name="theme-color" content="' + esc(colors.theme_color) + '">');

    // ── Apple touch icon (largest available) ──
    var appleSizes = [180, 192, 512];
    var appleSrc = '';
    for (var a = 0; a < appleSizes.length; a++) {
      var keyA = String(appleSizes[a]) + 'x' + appleSizes[a];
      if (fileMap['image/png'] && fileMap['image/png'][keyA] && fileMap['image/png'][keyA].src) {
        appleSrc = baseUrl + fileMap['image/png'][keyA].src;
        break;
      }
    }
    if (appleSrc) {
      lines.push('<link rel="apple-touch-icon" href="' + esc(appleSrc) + '">');
    }

    // ── Android / Chrome Web App manifest link (if browserconfig is present) ──
    if (fileMap['application/json'] && fileMap['application/json']['browserconfig.xml']) {
      var bcSrc = baseUrl + fileMap['application/json']['browserconfig.xml'].src;
      lines.push('<meta name="msapplication-config" content="' + esc(bcSrc) + '">');
    }

    // ── Windows tile colours ──
    lines.push('<meta name="msapplication-TileColor" content="' + esc(colors.background_color) + '">');
    lines.push('<meta name="msapplication-TileImage" content="' + esc(appleSrc) + '">');

    // ── Web App Manifest (generated by favicon-generator alongside the icon bundle) ──
    if (fileMap['application/json'] && fileMap['application/json']['manifest.json']) {
      var mfSrc = baseUrl + fileMap['application/json']['manifest.json'].src;
      lines.push('<link rel="manifest" href="' + esc(mfSrc) + '">');
    }

    // ── Favicon <link> entries grouped by MIME type ──
    var mimeOrder = ['image/png', 'image/webp', 'image/x-icon'];
    var fallbackIconSrc = null;   // first source found, used as fallback
    var fallbackIconType = options.iconType || 'image/png';
    var fallbackIconSize = null;

    mimeOrder.forEach(function (mime) {
      var group = fileMap[mime];
      if (!group || typeof group !== 'object') return;

      Object.keys(group).sort(function (a, b) {
        return parseInt(a, 10) - parseInt(b, 10);
      }).forEach(function (sizeKey) {
        var entry = group[sizeKey];
        if (!entry || !entry.src) return;

        var src = baseUrl + entry.src;
        var sizeMatch = String(sizeKey).match(/^(\d+)(?:x\d+)?$/);
        var sizeVal = sizeMatch ? parseInt(sizeMatch[1], 10) : null;

        // Prefer smallest integer size for the canonical icon tag; fall back to
        // width/height attributes when the size key encodes a × dimension.
        var dims = String(sizeKey).match(/^(\d+)x(\d+)$/);

        if (!fallbackIconSrc) {
          fallbackIconSrc  = src;
          fallbackIconType = mime;
          fallbackIconSize = sizeVal;
        }

        // Use explicit pixel sizes only for entries listed in FAVICON_SIZES so
        // that non-standard manifest/icon entries don't pollute the output.
        var sizeNum = sizeVal !== null && FAVICON_SIZES.indexOf(sizeVal) !== -1;
        if (dims && sizeNum) {
          lines.push(
            '<link rel="icon" ' +
            'type="' + esc(mime) + '" ' +
            'sizes="' + esc(sizeKey) + '" ' +
            'href="' + esc(src) + '">'
          );
        } else if (sizeNum) {
          lines.push(
            '<link rel="icon" ' +
            'type="' + esc(mime) + '" ' +
            'href="' + esc(src) + '">'
          );
        }
      });
    });

    // ── Canonical fallback <link rel="icon"> (smallest size, first declared MIME) ──
    if (fallbackIconSrc) {
      var relParts = ['rel="icon"'];
      relParts.push('type="' + esc(fallbackIconType) + '"');
      if (fallbackIconSize) {
        relParts.push('sizes="' + esc(fallbackIconSize) + 'x' + esc(fallbackIconSize) + '"');
      }
      relParts.push('href="' + esc(fallbackIconSrc) + '"');
      lines.push('<link ' + relParts.join(' ') + '>');
    }

    // ── ICO binary entry (if present, add as a dedicated icon link) ──
    if (fileMap['image/x-icon'] && fileMap['image/x-icon']['default']) {
      var icoSrc = baseUrl + fileMap['image/x-icon']['default'].src;
      // Only emit if not already covered by the generic fallback above.
      if (icoSrc !== fallbackIconSrc) {
        lines.push(
          '<link rel="icon" type="image/x-icon" href="' + esc(icoSrc) + '">'
        );
      }
    }

    // Join without trailing whitespace; one trailing newline is conventional.
    return lines.join('\n') + '\n';
  }

  // Export for both module systems and bare-script usage.
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = { snippet: snippet };
  }
  if (typeof global.snippetGenerator === 'undefined') {
    global.snippetGenerator = { snippet: snippet };
  }
})(typeof window !== 'undefined' ? window : global);